// Package agentmark marks agent files written by ethos so that later readers
// can tell them from hand-authored ones.
package agentmark

import "strings"

// Line is the provenance marker. It is a YAML comment on the first line
// inside the frontmatter, so the frontmatter stays valid YAML and Claude
// Code's agent loader ignores it.
const Line = "# generated by ethos — edit .punt-labs/ethos, not this file"

// Add returns content with the marker as the first frontmatter line, in the
// file's own line ending (LF or CRLF). It is idempotent. Content with no
// frontmatter is returned unchanged: there is no YAML to hold the marker, and
// inventing a frontmatter would change how the file loads.
func Add(content string) string {
	nl := newline(content)
	if nl == "" || Has(content) {
		return content
	}
	return "---" + nl + Line + nl + content[len("---"+nl):]
}

// Has reports whether content carries the marker.
func Has(content string) bool {
	nl := newline(content)
	return nl != "" && strings.HasPrefix(content, "---"+nl+Line+nl)
}

// newline returns the line ending of the opening frontmatter fence, or ""
// if content does not start with one.
func newline(content string) string {
	switch {
	case strings.HasPrefix(content, "---\r\n"):
		return "\r\n"
	case strings.HasPrefix(content, "---\n"):
		return "\n"
	}
	return ""
}
